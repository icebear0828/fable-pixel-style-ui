export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, "name"> {
  /** 图标名称 */
  name: IconName;
  /** 尺寸（px） */
  size?: number | string;
  /** 颜色，默认 currentColor */
  color?: string;
  /** 旋转动画 */
  spin?: boolean;
}

export const Icon: React.FC<IconProps> = ({ name, size = 16, color = "currentColor", spin, className, style, ...rest }) => {
  const grid = ICONS[name] as readonly string[];
  const w = grid[0].length;
  const h = grid.length;
  return (
    <svg
      className={cx("pxui-icon", spin && "pxui-icon--spin", className)}
      width={size}
      height={size}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      style={style}
      {...rest}
    >
      <path fill={color} d={gridToPath([...grid])} />
    </svg>
  );
};

Icon.displayName = "Icon";
